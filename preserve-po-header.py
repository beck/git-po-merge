#!/usr/bin/env python3
"""
Merge PO header comments and metadata using BASE, LOCAL, and OTHER.

Usage: preserve-po-header.py BASE LOCAL OTHER MERGED OUTPUT

MERGED is the PO catalog produced by the translation merge algorithm.
The comments preceding its metadata entry and the metadata fields are
replaced by the three-way-merged header from BASE, LOCAL, and OTHER.
Unrelated translation entries come from MERGED.

Header comments are merged as a whole block. Metadata is merged per key.
Ambiguous concurrent changes fail without modifying OUTPUT.
"""

import os
from pathlib import Path
import sys
import tempfile

try:
    import polib
except ImportError:
    sys.exit('PO header merge failed: polib is required (python3 -m pip install polib)')

COMMENT = '# header-comments #'
GETTEXT_DEFAULTS = {
    'Project-Id-Version': {'PACKAGE VERSION'},
    'PO-Revision-Date': {'YEAR-MO-DA HO:MI+ZONE'},
    'Last-Translator': {'FULL NAME <EMAIL@ADDRESS>'},
    'Language-Team': {'LANGUAGE <LL@li.org>'},
    'Content-Type': {'text/plain; charset=CHARSET'},
    COMMENT: {'SOME DESCRIPTIVE TITLE.', 'Generated by grunt'}
}
DEFAULT_METADATA = {
    'Content-Type': 'text/plain; charset=UTF-8',
    'MIME-Version': '1.0',
}


class Missing:
    def __repr__(self):
        return '<missing>'
    __str__ = __repr__


MISSING = Missing()


def main():
    if len(sys.argv) != 6:
        sys.exit('Usage: preserve-po-header.py BASE LOCAL OTHER MERGED OUTPUT')

    base, local, other, merged, output = map(Path, sys.argv[1:])

    base_po = polib.pofile(str(base), check_for_duplicates=True)
    local_po = polib.pofile(str(local), check_for_duplicates=True)
    other_po = polib.pofile(str(other), check_for_duplicates=True)
    merged_po = polib.pofile(str(merged), check_for_duplicates=True, wrapwidth=80)

    header = merge_metadata_value(
        COMMENT,
        base_po.header,
        local_po.header,
        other_po.header,
    )
    merged_po.header = '' if header is MISSING else header
    if not other_po.metadata:
        merged_po.metadata = local_po.metadata.copy() or DEFAULT_METADATA.copy()
    elif not local_po.metadata:
        merged_po.metadata = other_po.metadata.copy() or DEFAULT_METADATA.copy()
    else:
        merged_po.metadata = merge_metadata(
            base_po.metadata,
            local_po.metadata,
            other_po.metadata,
        )
    # header metadata was successfully merged; remove stale fuzzy flag
    merged_po.metadata_is_fuzzy = False

    # write atomically: failures must not partially overwrite Git's output
    temp_path = None
    try:
        with tempfile.NamedTemporaryFile(
            prefix='.po-header-',
            suffix='.po',
            dir=output.parent,
            delete=False,
        ) as fd:
            temp_path = Path(fd.name)

        merged_po.wrapwidth = 80
        merged_po.save(str(temp_path))

        # polib emits a synthetic '#' line for an empty header comment block
        # remove it only if it is the very first line and no comments exist
        if not merged_po.header:
            content = temp_path.read_bytes()
            if content.startswith(b'#\n'):
                temp_path.write_bytes(content[2:])

        os.replace(temp_path, output)
    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)


def merge_metadata(base, local, other):
    merged = {}
    # dicts preserve insertion order; prefer the local order where possible
    keys = dict.fromkeys((*local, *other, *base))
    for key in keys:
        value = merge_metadata_value(
            key,
            base.get(key, MISSING),
            local.get(key, MISSING),
            other.get(key, MISSING),
        )
        if value is not MISSING:
            merged[key] = value
    return merged or DEFAULT_METADATA.copy()


def merge_metadata_value(key, base, local, other):
    base = normalize_metadata(key, base)
    local = normalize_metadata(key, local)
    other = normalize_metadata(key, other)

    # Identical values, including both missing
    if local == other:
        return local

    # Missing metadata should not overwrite existing information
    if local is MISSING:
        return other

    if other is MISSING:
        return local

    # Standard three-way merge for meaningful values
    if local == base:
        return other

    if other == base:
        return local

    return str(ValueError(f'Conflicting PO metadata field {key!r}: base={base!r}, local={local!r}, other={other!r}'))


def normalize_metadata(key, value):
    if value is MISSING or not value:
        return MISSING

    if value in GETTEXT_DEFAULTS.get(key, set()):
        return MISSING
    if key == COMMENT and any(string in value for string in GETTEXT_DEFAULTS[COMMENT]):
        return MISSING

    return value


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError) as exc:
        sys.exit(f'PO header merge failed: {exc}')
